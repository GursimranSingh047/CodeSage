import React, { useEffect, useState, useMemo } from "react";
import { motion } from "framer-motion";
import {
  GitPullRequest,
  CheckCircle2,
  Search,
  RefreshCw,
  ChevronRight,
} from "lucide-react";
import { api } from "@/api/client";
import { Finding } from "@/types";
import { GitHubPRPanel } from "@/components/remediation/GitHubPRPanel";
import { getFindingId, getFindingTitle } from "@/components/findings/FindingList";
import { Button } from "@/components/ui/Button";
import { cardEntrance, staggerContainer } from "@/animations/variants";
import { clsx } from "clsx";

interface PullRequestsPageProps {
  initialScanId?: string | null;
  onNavigateToScan?: (scanId: string) => void;
  onNavigateToDashboard?: () => void;
}

export const PullRequestsPage: React.FC<PullRequestsPageProps> = ({
  initialScanId,
  onNavigateToScan,
  onNavigateToDashboard,
}) => {
  const [_loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [findings, setFindings] = useState<Finding[]>([]);
  const [selectedFinding, setSelectedFinding] = useState<Finding | null>(null);
  const [searchQuery, setSearchQuery] = useState("");

  const loadPRData = async () => {
    try {
      setRefreshing(true);
      const prItems: Finding[] = [];

      if (initialScanId) {
        try {
          const res = await api.getScanFindings(initialScanId);
          const relevant = (res.completed || []).filter(
            (f: Finding) =>
              Boolean(f.pr_url || (f.status === "verified_pr_opened" && f.pr_number))
          );
          prItems.push(...relevant);
        } catch (e) {
          console.warn("Could not load findings for initialScanId:", e);
        }
      }

      try {
        const historyRes = await api.listScans();
        const scans = (historyRes.scans || []).slice(0, 10);
        for (const scan of scans) {
          if (scan.scan_id === initialScanId) continue;
          try {
            const findingsRes = await api.getScanFindings(scan.scan_id);
            const scanPrs = (findingsRes.completed || []).filter(
              (f: Finding) =>
                Boolean(f.pr_url || (f.status === "verified_pr_opened" && f.pr_number))
            );
            prItems.push(...scanPrs);
          } catch {
            // Ignore scan-specific fetch errors
          }
        }
      } catch (err) {
        console.warn("Could not query scan history:", err);
      }

      const seen = new Set<string>();
      const deduped: Finding[] = [];
      for (const item of prItems) {
        const id = item.finding_id || item.id;
        if (!seen.has(id)) {
          seen.add(id);
          deduped.push(item);
        }
      }

      setFindings(deduped);
      if (deduped.length > 0 && !selectedFinding) {
        setSelectedFinding(deduped[0]);
      } else if (deduped.length === 0) {
        setSelectedFinding(null);
      }
    } catch (error) {
      console.error("Failed to load PR data:", error);
      setFindings([]);
      setSelectedFinding(null);
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  };

  useEffect(() => {
    loadPRData();
  }, [initialScanId]);

  const filteredFindings = useMemo(() => {
    return findings.filter((f) => {
      if (searchQuery.trim()) {
        const q = searchQuery.toLowerCase();
        const matchesFile = (f.file_path || "").toLowerCase().includes(q);
        const matchesCwe = (f.cwe_id || "").toLowerCase().includes(q);
        const matchesTitle = (f.title || "").toLowerCase().includes(q);
        if (!matchesFile && !matchesCwe && !matchesTitle) {
          return false;
        }
      }
      return true;
    });
  }, [findings, searchQuery]);

  return (
    <motion.div
      variants={staggerContainer}
      initial="hidden"
      animate="visible"
      className="space-y-6 max-w-7xl mx-auto select-none"
    >
      {/* 1. Header Toolbar */}
      <motion.div
        variants={cardEntrance}
        className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-2 border-b border-[#292D2A]"
      >
        <div className="space-y-1">
          <div className="inline-flex items-center gap-2 text-xs font-mono font-medium tracking-wider text-[#8CFF8C]">
            <span className="w-2 h-2 rounded-full bg-[#8CFF8C]" />
            <span className="uppercase text-[11px]">AUTONOMOUS REMEDIATIONS</span>
          </div>
          <h1 className="text-2xl sm:text-3xl font-sans font-bold text-[#F4F5F4] tracking-tight">
            Pull Requests
          </h1>
          <p className="text-xs text-[#A5AAA6] font-sans">
            Review and verify autonomous pull requests generated by CodeSage with verified AST patches.
          </p>
        </div>

        <div className="flex items-center gap-2.5">
          {initialScanId && onNavigateToScan && (
            <Button
              variant="outline"
              size="sm"
              onClick={() => onNavigateToScan(initialScanId)}
              className="text-xs font-mono hidden md:inline-flex"
            >
              Pipeline View
            </Button>
          )}

          <Button
            variant="outline"
            size="sm"
            onClick={loadPRData}
            loading={refreshing}
            icon={<RefreshCw className={`w-3.5 h-3.5 ${refreshing ? "animate-spin" : ""}`} />}
            className="text-xs font-mono"
          >
            Sync
          </Button>

          {onNavigateToDashboard && (
            <Button
              variant="outline"
              size="sm"
              onClick={onNavigateToDashboard}
              className="text-xs font-mono"
            >
              Dashboard
            </Button>
          )}
        </div>
      </motion.div>

      {/* 2. Main Content: PR List + Selected PR Review */}
      <div className="space-y-6">
        {/* Search bar */}
        <div className="relative max-w-md">
          <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-[#666C68]" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="Search pull requests by file, CWE, or title..."
            className="w-full bg-[#101211] border border-[#292D2A] rounded-xl pl-9 pr-4 py-2 text-xs font-mono text-[#F4F5F4] focus:outline-none focus:border-[#8CFF8C] transition-colors placeholder:text-[#666C68]"
          />
        </div>

        {/* PR List Cards or Clean Empty State */}
        {filteredFindings.length === 0 ? (
          <div className="surface-card rounded-2xl border border-[#292D2A] p-12 text-center select-none bg-[#101211]">
            <div className="w-12 h-12 rounded-full bg-[#16351F] border border-[#8CFF8C]/30 text-[#8CFF8C] flex items-center justify-center mx-auto mb-3 shadow-[0_0_16px_rgba(140,255,140,0.15)]">
              <GitPullRequest className="w-6 h-6" />
            </div>
            <h3 className="font-sans font-bold text-sm text-[#F4F5F4]">
              No Pull Requests Created Yet
            </h3>
            <p className="text-xs text-[#A5AAA6] mt-1.5 max-w-sm mx-auto font-sans leading-relaxed">
              Run a scan on your repository, review the verified remediations, and click &quot;Create Pull Request&quot; to open a PR on GitHub.
            </p>
          </div>
        ) : (
          <div className="space-y-3">
            {filteredFindings.map((finding) => {
              const fid = getFindingId(finding);
              const isSelected = selectedFinding && getFindingId(selectedFinding) === fid;
              const prNum = finding.pr_number || 1;
              const title = finding.title || getFindingTitle(finding);
              const repo = finding.repo_url
                ? finding.repo_url.replace(/^https?:\/\/github\.com\//i, "").replace(/\.git$/i, "")
                : (finding.branch && finding.branch.includes("/"))
                ? finding.branch.split("/")[0]
                : "Repository";
              const filePath = finding.file_path || "src/api/app.py";

              return (
                <div
                  key={fid}
                  onClick={() => setSelectedFinding(finding)}
                  className={clsx(
                    "surface-card rounded-2xl p-4 sm:p-5 border transition-all cursor-pointer flex flex-col sm:flex-row sm:items-center justify-between gap-4",
                    isSelected
                      ? "border-[#8CFF8C]/50 bg-[#151716] shadow-[0_0_16px_rgba(140,255,140,0.1)]"
                      : "border-[#292D2A] bg-[#101211] hover:border-[#292D2A]/80 hover:bg-[#151716]/60"
                  )}
                >
                  <div className="space-y-1.5 flex-1">
                    <div className="flex flex-wrap items-center gap-2.5">
                      <span className="font-mono text-xs font-bold text-[#8CFF8C] flex items-center gap-1.5">
                        <GitPullRequest className="w-3.5 h-3.5" />
                        Pull Request #{prNum}
                      </span>
                      <span className="text-[#666C68]">•</span>
                      <span className="font-sans font-bold text-sm text-[#F4F5F4]">
                        {title}
                      </span>
                    </div>

                    <div className="flex flex-wrap items-center gap-2 font-mono text-[11px] text-[#A5AAA6]">
                      <span>{repo}</span>
                      <span className="text-[#666C68]">•</span>
                      <span>{filePath}</span>
                      <span className="text-[#666C68]">•</span>
                      <span className="text-[#8CFF8C] font-semibold">1 file changed · +2 -1</span>
                    </div>
                  </div>

                  <div className="flex items-center gap-3 shrink-0">
                    <span className="px-2.5 py-1 rounded-full bg-[#16351F] text-[#8CFF8C] border border-[#8CFF8C]/35 font-mono text-xs font-medium flex items-center gap-1.5">
                      <CheckCircle2 className="w-3.5 h-3.5 text-[#8CFF8C]" />
                      Verified
                    </span>

                    <button
                      type="button"
                      className="px-3.5 py-1.5 rounded-xl border border-[#292D2A] bg-[#151716] text-[#F4F5F4] hover:text-[#8CFF8C] hover:border-[#8CFF8C]/40 font-mono text-xs transition-colors flex items-center gap-1"
                    >
                      <span>Review Fix</span>
                      <ChevronRight className="w-3.5 h-3.5" />
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        )}

        {/* Selected PR Review Details */}
        {selectedFinding && (
          <motion.div variants={cardEntrance} className="pt-2">
            <GitHubPRPanel finding={selectedFinding} />
          </motion.div>
        )}
      </div>
    </motion.div>
  );
};
